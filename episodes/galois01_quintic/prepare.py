def stamp(t):
    return f'{t//3600:02}:{t//60%60:02}:{t%60:02},000'

def main():
    sentences=[]
    start=0
    for line in LINES.splitlines():
        end, text=line.split('|',1)
        end=int(end)
        sentences.append(dict(start=start,end=end,text=text))
        start=end
    scenes=[dict(id=f'{i:02}',start=a,end=b,title=t,**{'class':f'Shot{i:02}'})
            for i,(a,b,t) in enumerate(SHOTS,1)]
    data=dict(title='왜 5차 방정식에는 근의 공식이 없을까?',duration=162,
              sentences=sentences,scenes=scenes)
    (HERE/'timing.json').write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    (HERE/'captions.srt').write_text('\n\n'.join(f"{i}\n{stamp(s['start'])} --> {stamp(s['end'])}\n{s['text']}"
        for i,s in enumerate(sentences,1))+'\n',encoding='utf-8')
    (HERE/'narration.md').write_text('# '+data['title']+'\n\n사용자 제공 확정 대본 · 문장 종료 시각(초)\n\n'+
        '\n'.join(f"- {s['end']}초 · {s['text']}" for s in sentences)+'\n',encoding='utf-8')
    blocks=[]
    for a,b,_ in SHOTS:
        block=' '.join(s['text'] for s in sentences if a<=s['start']<b)
        for old,new in [('S5','에스 파이브'),('A5','에이 파이브'),('2차','이차'),('3차','삼차'),('4차','사차'),('5차','오차'),('5x','오 엑스'),('x제곱','엑스 제곱')]:
            block=block.replace(old,new)
        for old,new in [('2','이'),('3','삼'),('5','오'),('6','육')]:
            block=block.replace(old,new)
        blocks.append(block)
    (HERE/'tts_script.txt').write_text('\n\n'.join(blocks)+'\n',encoding='utf-8')

if __name__=='__main__':
    main()
